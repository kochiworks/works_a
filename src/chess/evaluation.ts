function mirrorIndex(index: number): number {
  const rank = Math.floor(index / 8)
  const file = index % 8
  return (7 - rank) * 8 + file
}

/** Material + positional score from White's perspective (positive favors White). */
export function evaluateMaterial(chess: Chess): number {
  let score = 0
  const board = chess.board()
  for (let rank = 0; rank < 8; rank++) {
    for (let file = 0; file < 8; file++) {
      const cell = board[rank][file]
      if (!cell) continue
      const index = rank * 8 + file
      const pst = PST[cell.type]
      const positional = cell.color === 'w' ? pst[index] : pst[mirrorIndex(index)]
      const total = PIECE_VALUES[cell.type] + positional
      score += cell.color === 'w' ? total : -total
    }
  }
  return score
}

/** Score from the perspective of the side to move (positive = good for them). */
export function evaluatePerspective(chess: Chess, sideToMove: Color): number {
  const raw = evaluateMaterial(chess)
  return sideToMove === 'w' ? raw : -raw
}
